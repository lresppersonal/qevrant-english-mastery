"use client";
import Link from "next/link";
import clsx from "clsx";
import { BookOpen, Info, ArrowRight } from "lucide-react";
import { grammarDomains, getLesson, getSense } from "@/lib/content";
import { CRITERIA_LABEL, RATING_LABEL, RATING_ORDER, type SpeakingFeedback, type WritingFeedback } from "@/lib/ai/schemas";
import { LevelBadge } from "./ui";
import { SaveButton } from "./SaveButton";

type Fb = WritingFeedback | SpeakingFeedback;
const CATEGORY: Record<string, string> = { grammar: "Grammar", vocabulary: "Vocabulary", cohesion: "Cohesion", register: "Register", task: "Task", spelling_punctuation: "Spelling & punctuation" };

export function GrammarRefLink({ refId }: { refId: string | null }) {
  if (!refId) return null;
  if (refId.startsWith("lesson:")) {
    const [slug, section] = refId.slice(7).split("#");
    const lesson = getLesson(slug);
    const sec = lesson?.sections.find((s) => s.id === section);
    if (!lesson) return null;
    return (
      <Link href={`/grammar/${slug}#${section}`} className="inline-flex items-center gap-1 text-sm font-semibold text-primary underline-offset-4 hover:underline">
        <BookOpen size={14} aria-hidden="true" /> Review the rule: {sec?.title ?? lesson.title}
      </Link>
    );
  }
  const d = grammarDomains.find((x) => `domain:${x.key}` === refId);
  if (!d) return null;
  return <Link href={`/grammar#${d.key}`} className="inline-flex items-center gap-1 text-sm font-semibold text-primary underline-offset-4 hover:underline"><BookOpen size={14} aria-hidden="true" /> Grammar area: {d.title}</Link>;
}

function RatingMeter({ rating }: { rating: (typeof RATING_ORDER)[number] }) {
  const idx = RATING_ORDER.indexOf(rating);
  return (
    <div className="flex items-center gap-2" aria-label={`Rating: ${RATING_LABEL[rating]}`}>
      <div className="flex gap-1" aria-hidden="true">
        {RATING_ORDER.map((r, i) => <span key={r} className={clsx("h-2 w-7 rounded-full", i <= idx ? "bg-primary" : "bg-surface-2")} />)}
      </div>
      <span className="text-sm font-semibold">{RATING_LABEL[rating]}</span>
    </div>
  );
}

/** The learner's own text with issue quotes highlighted and numbered. */
export function AnnotatedText({ text, quotes }: { text: string; quotes: string[] }) {
  const marks: { start: number; end: number; n: number }[] = [];
  const lower = text.toLowerCase();
  quotes.forEach((q, n) => {
    const at = lower.indexOf(q.toLowerCase().replace(/[.,;:!?]+$/, ""));
    if (at >= 0 && !marks.some((m) => at < m.end && at + q.length > m.start)) marks.push({ start: at, end: at + q.replace(/[.,;:!?]+$/, "").length, n: n + 1 });
  });
  marks.sort((a, b) => a.start - b.start);
  const out: React.ReactNode[] = [];
  let pos = 0;
  for (const m of marks) {
    out.push(text.slice(pos, m.start));
    out.push(<mark key={m.n} className="rounded bg-[color-mix(in_srgb,var(--accent)_30%,transparent)] px-0.5 text-ink">{text.slice(m.start, m.end)}<sup className="ml-0.5 font-bold text-accent-text">{m.n}</sup></mark>);
    pos = m.end;
  }
  out.push(text.slice(pos));
  return <div className="whitespace-pre-wrap text-[16px] leading-[1.8]">{out}</div>;
}

